"""Embed version-specific JSON into C++ to keep the runtime distribution one DLL."""
from __future__ import annotations
from pathlib import Path
import json


def make_header(source: Path, destination: Path) -> None:
    data = source.read_text(encoding="utf-8")
    value = json.loads(data)
    if value.get("schema") != 1 or "symbols" not in value:
        raise ValueError("expected a Bedrock symbol database schema 1")
    marker = "BEDROCK_SYMBOLS_DH2C"
    if f"){marker}\"" in data:
        raise ValueError("raw string marker collision")
    header = (
        "#pragma once\n"
        "// Generated by bedrock-symbols embed. Do not manually edit.\n"
        "namespace bedrock::generated {\n"
        "inline constexpr const char* kSymbolDatabase = R\"" + marker + "("
        + data + ")" + marker + "\";\n"
        "} // namespace bedrock::generated\n"
    )
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(header, encoding="utf-8")
